export const getExamQuestions = (): Question[] => {
  // Stratified sample from all categories
  const perCategory = Math.ceil(50 / 9)
  const selected: Question[] = []
  const categories = [...new Set(QUESTIONS.map(q => q.category))]
  for (const cat of categories) {
    const catQ = getByCategory(cat)
    const shuffled = [...catQ].sort(() => Math.random() - 0.5)
    selected.push(...shuffled.slice(0, perCategory))
  }
  return selected.sort(() => Math.random() - 0.5).slice(0, 50)
}

export const getQuestionsByIds = (ids: string[]): Question[] =>
  QUESTIONS.filter(q => ids.includes(q.id))
